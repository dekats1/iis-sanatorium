    private static String pick(Random rng, String[] a) {
        return a[rng.nextInt(a.length)];
    }

    private static int tier(int rating) {
        return rating >= 4 ? 0 : rating == 3 ? 1 : 2;
    }

    public static String reviewComment(Random rng, int overall, int room, int treatment, int food, int service) {
        int t = tier(overall);
        String open = t == 0 ? pick(rng, OPEN_GOOD) : t == 1 ? pick(rng, OPEN_MID) : pick(rng, OPEN_BAD);
        String close = t == 0 ? pick(rng, CLOSE_GOOD) : t == 1 ? pick(rng, CLOSE_MID) : pick(rng, CLOSE_BAD);
        return open + " " + pick(rng, ROOM[tier(room)]) + " " + pick(rng, TREATMENT[tier(treatment)]) + " "
                + pick(rng, FOOD[tier(food)]) + " " + pick(rng, SERVICE[tier(service)]) + " " + close;
    }

