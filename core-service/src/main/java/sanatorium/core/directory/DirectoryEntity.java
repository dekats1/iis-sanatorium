package sanatorium.core.directory;

/**
 * Запись справочника. Сущность одновременно служит телом REST-запроса и ответа: поля справочников плоские,
 * ссылки на другие записи хранятся идентификаторами, ленивых связей нет. {@code copyFrom} переносит
 * изменяемые поля (идентификатор не переносится) — так реализована полная замена в PUT.
 */
public interface DirectoryEntity<E> {

    void copyFrom(E source);
}
